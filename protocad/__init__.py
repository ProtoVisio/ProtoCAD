"""ProtoCAD — самостоятельное приложение для конструирования электронных изделий.

Собирается на OCCT напрямую: FreeCAD в качестве зависимости не требуется
(Spike 4). Он остаётся справочником по реализации, не более.

Состав:

* ``kernel``  — геометрия на OCCT: тела, операции, тесселяция, проекции;
* ``sketch``  — параметрический эскиз со сменным решателем ограничений;
* ``model``   — объектная модель по ЕСКД: изделия, состав, спецификация;
* ``format``  — файлы ``.prcadPart`` / ``.prcadAsm`` / ``.prcadDraw``;
* ``drawing`` — чертежи по ГОСТ.

Читатель файлов и просмотрщик живут ОТДЕЛЬНЫМИ проектами
(``protocad_reader``, ``protocad_viewer``): они предназначены для встраивания
в ПРОТО, который закрытый и коммерческий, поэтому их лицензионный контур
должен быть независим от контура ядра.
"""

